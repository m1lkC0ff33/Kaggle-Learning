# ==========================================
# 1. 乘法交互 (Multiplication: X * Y)
# 什么时候用：当两个特征之间存在“协同效应”或“条件约束”时。
# 场景 A：单位价值。如 (单价 * 数量) = 总额。
# 场景 B：放大效应。如 (学习时长 * 专注度) = 实际效率。
# 场景 C：权重修正。如 (工作年限 * 技术评分)。
# ==========================================
# 逻辑：单独的学习时长很有用，但如果专注度为0，时长再多也没用。乘法能捕捉这种“一荣俱荣”的关系。
train['study_effectiveness'] = train['study_hours'] * train['focus_score']


# ==========================================
# 2. 除法交互 (Division: X / Y)
# 什么时候用：计算“密度”、“占比”或“单位成本”。
# 场景 A：效率比率。如 (分数 / 学习时间)。
# 场景 B：相对排名。如 (个人消费 / 家庭平均消费)。
# 场景 C：资源分配。如 (人口 / 土地面积)。
# ==========================================
# 逻辑：除法用于消除“规模”的影响。
# 两个学生都考了80分，但一个学了10小时，一个学了2小时，除法能凸显后者的“高效率”。
train['score_per_hour'] = train['exam_score'] / (train['study_hours'] + 1e-5) # 加极小值防报错


# ==========================================
# 3. 加减法交互 (Addition/Subtraction: X ± Y)
# 什么时候用：计算“净值”、“差距”或“总和”。
# 场景 A：时间差。如 (考试日期 - 注册日期)。
# 场景 B：盈余。如 (总收入 - 总支出)。
# 场景 C：综合得分。如 (数学分 + 语文分 + 英语分)。
# ==========================================
# 逻辑：减法最常用于衡量“偏离度”。
# 如 (学生分数 - 班级平均分)，负数表示低于平均，正数表示优异。
train['score_diff_from_mean'] = train['exam_score'] - train['class_avg_score']


# ==========================================
# 4. 多项式特征 (Polynomial: X²)
# 什么时候用：当你发现特征与目标之间不是线性关系，而是“抛物线”关系。
# 场景：年龄与体力的关系。体力随年龄增长，但过了巅峰期会下降。
# ==========================================
# 逻辑：平方项可以让模型捕捉到“物极必反”的非线性趋势。
train['age_squared'] = train['age'] ** 2


# ==========================================
# 5. 分桶/离散化 (Binning)
# 什么时候用：当数值的微小变化不重要，而“区间”很重要时。
# 场景：年龄（20岁和21岁没区别，但20岁和60岁有本质区别）。
# ==========================================
# 逻辑：把连续值变成分类值，降低模型学习的噪音。
train['age_group'] = pd.cut(train['age'], bins=[0, 18, 35, 60, 100], labels=['Youth', 'Adult', 'Middle', 'Senior'])